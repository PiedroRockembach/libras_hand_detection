"""Canonical data registry schema (ADR-0010).

Five tables, stored as UTF-8 CSV. `sources`, `glosses` and `label_map` are curated and
versioned in git (metadata/registry/); `signers` and `samples` are generated by source
adapters and live in LIBRAS_DATA_ROOT/registry/ (ADR-0011).
"""

from __future__ import annotations

from dataclasses import dataclass, field

TRISTATE = ("yes", "no", "unknown")


@dataclass(frozen=True)
class Column:
    name: str
    required: bool = False
    kind: str = "str"  # "str" | "int" | "float"
    choices: tuple[str, ...] | None = None
    unique: bool = False


@dataclass(frozen=True)
class ForeignKey:
    column: str
    table: str
    target: str


@dataclass(frozen=True)
class Table:
    name: str
    columns: tuple[Column, ...]
    key: tuple[str, ...]
    foreign_keys: tuple[ForeignKey, ...] = field(default_factory=tuple)

    @property
    def column_names(self) -> list[str]:
        return [c.name for c in self.columns]


SOURCES = Table(
    name="sources",
    columns=(
        Column("source_id", required=True, unique=True),
        Column("name", required=True),
        Column("version"),
        Column("url", required=True),
        Column("license", required=True),
        Column("redistribution", required=True, choices=TRISTATE),
        Column("commercial_use", required=True, choices=TRISTATE),
        Column("datasheet"),
    ),
    key=("source_id",),
)

GLOSSES = Table(
    name="glosses",
    columns=(
        Column("gloss_id", required=True, unique=True),
        Column("gloss", required=True),
        Column("unit", required=True, choices=("sign", "phrase")),
        Column("variant"),
        Column("signbank_ref"),
        Column("ines_ref"),
        Column("notes"),
    ),
    key=("gloss_id",),
)

LABEL_MAP = Table(
    name="label_map",
    columns=(
        Column("source_id", required=True),
        Column("source_label", required=True),
        Column("gloss_id", required=True),
    ),
    key=("source_id", "source_label"),
    foreign_keys=(
        ForeignKey("source_id", "sources", "source_id"),
        ForeignKey("gloss_id", "glosses", "gloss_id"),
    ),
)

SIGNERS = Table(
    name="signers",
    columns=(
        Column("signer_uid", required=True, unique=True),
        Column("source_id", required=True),
        Column("source_signer_id", required=True),
        Column("same_person_as"),
        Column("hearing_status", choices=("deaf", "hard_of_hearing", "hearing", "unknown")),
        Column("region"),
        Column("age_band"),
        Column("handedness", choices=("right", "left", "unknown")),
    ),
    key=("signer_uid",),
    foreign_keys=(
        ForeignKey("source_id", "sources", "source_id"),
        ForeignKey("same_person_as", "signers", "signer_uid"),
    ),
)

SAMPLES = Table(
    name="samples",
    columns=(
        Column("sample_id", required=True, unique=True),
        Column("source_id", required=True),
        Column("gloss_id", required=True),
        Column("signer_uid", required=True),
        Column("path", required=True),
        Column("media", required=True, choices=("video", "frames_tensor")),
        Column("start_frame", kind="int"),
        Column("end_frame", kind="int"),
        Column("fps", kind="float"),
        Column("width", kind="int"),
        Column("height", kind="int"),
        Column("n_frames", kind="int"),
        Column("camera"),
        Column("background"),
        Column("lighting"),
        Column("license", required=True),
        Column(
            "consent_scope",
            required=True,
            choices=("public_license", "research_only", "partner_agreement", "unknown"),
        ),
        Column("video_sha256"),
        Column("quality_flags"),  # ";"-separated
    ),
    key=("sample_id",),
    foreign_keys=(
        ForeignKey("source_id", "sources", "source_id"),
        ForeignKey("gloss_id", "glosses", "gloss_id"),
        ForeignKey("signer_uid", "signers", "signer_uid"),
    ),
)

TABLES: dict[str, Table] = {t.name: t for t in (SOURCES, GLOSSES, LABEL_MAP, SIGNERS, SAMPLES)}

# Which tables are curated in git and which are generated into the data root (ADR-0011).
CURATED = ("sources", "glosses", "label_map")
GENERATED = ("signers", "samples")
